"""
NEXUS — Agent Structured Output Schemas
========================================
Defines strict Pydantic schemas for LLM agent outputs with validation and repair routines.
"""

from typing import List, Literal

from pydantic import BaseModel, Field, field_validator


class MitigationPlan(BaseModel):
    """
    Schema representing a validated supply chain mitigation action proposal.
    Derived directly from the fields produced by the mitigation graph.
    """
    action_type: Literal["dual_source", "reroute", "safety_stock", "alert_only"] = Field(
        ...,
        description="The operational category of the recommended mitigation action."
    )
    summary: str = Field(
        ...,
        min_length=5,
        max_length=300,
        description="Concise one-sentence executive summary of the mitigation."
    )
    rationale: str = Field(
        ...,
        min_length=10,
        max_length=1000,
        description="Detailed operational justification for selecting this course of action."
    )
    steps: List[str] = Field(
        default_factory=list,
        description="Ordered sequence of concrete operational steps required to execute."
    )
    estimated_cost_impact: str = Field(
        default="+0%",
        description="Estimated procurement or logistics financial impact (e.g. '+8-12%')."
    )
    estimated_risk_reduction: str = Field(
        default="Moderate",
        description="Expected post-mitigation risk score or reduction metric."
    )
    urgency: Literal["immediate", "within_48h", "this_week"] = Field(
        default="within_48h",
        description="Operational timeframe for executing the mitigation."
    )
    confidence: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description="Statistical or qualitative model confidence score between 0.0 and 1.0."
    )
    source: Literal["llm", "fallback", "repaired"] = Field(
        default="llm",
        description="Origin of the plan: generated by LLM, repaired, or deterministic fallback."
    )

    @field_validator("steps", mode="before")
    @classmethod
    def ensure_steps_list(cls, v):
        if isinstance(v, str):
            return [s.strip() for s in v.split("\n") if s.strip()]
        if not isinstance(v, list):
            return []
        return [str(item) for item in v if item]
